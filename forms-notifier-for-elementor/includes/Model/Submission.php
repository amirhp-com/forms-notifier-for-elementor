<?php
/**
 * Submission DTO.
 *
 * @package FormsNotifier
 */

namespace AmirhpCom\FormsNotifier\Model;

defined( 'ABSPATH' ) || exit;

/**
 * Normalised submission. Built by a FormSourceInterface adapter + Capture.
 *
 * Field shape (array, keyed by field id in $fields, order = form order):
 *   id       string   field custom id; unique within the form
 *   type     string   native type as reported (text, email, upload, acceptance, anything)
 *   label    string   label; falls back to the id when empty
 *   value    string   display value: scalar as string, arrays joined with ", ", files as names/links
 *   values   string[] list form of the value; single value => one item; empty => []
 *   raw      mixed    what the source reported (scalar|array), already sanitised; never trusted as markup
 *   is_file  bool
 *   redacted bool     true for password/sensitive fields; value is then masked, raw is ''
 *   hidden   bool     true = stored but excluded from {all_fields}
 */
final class Submission {

	/** @var int fnfe_submissions.id, 0 before save */
	public int $id = 0;

	/** @var string 32 hex, generated by Capture */
	public string $uuid = '';

	/** @var int fnfe_forms.id */
	public int $form_id = 0;

	/** @var string "{post_id}:{element_id}" */
	public string $form_key = '';

	/** @var int */
	public int $post_id = 0;

	/** @var string */
	public string $element_id = '';

	/** @var string */
	public string $source = 'pro';

	/** @var string */
	public string $form_name = '';

	/** @var array<string,array> */
	public array $fields = [];

	/** @var Attachment[] */
	public array $files = [];

	/** @var string */
	public string $lang = '';

	/** @var string new|read|done|spam|trash */
	public string $status = 'new';

	/** @var string 'Y-m-d H:i:s' UTC */
	public string $created_gmt = '';

	/**
	 * Keys (all optional, strings unless noted): page_url, page_title, queried_id (int), referrer, user_id (int),
	 * user_login, user_email, user_ip, user_agent, locale, via ('action'|'auto'|'api'|'test'),
	 * elementor_submission_id (int), action_errors (string[]), editor (array: editor override layer),
	 * utm (array<string,string>), delivery_status (string, filled when read from the database).
	 *
	 * @var array
	 */
	public array $meta = [];

	/**
	 * One field array, null when unknown.
	 *
	 * @param string $id Field id.
	 */
	public function field( string $id ): ?array {
		return isset( $this->fields[ $id ] ) && is_array( $this->fields[ $id ] ) ? $this->fields[ $id ] : null;
	}

	/**
	 * Display value of a field.
	 *
	 * @param string $id      Field id.
	 * @param string $default Returned when the field is unknown or empty.
	 */
	public function value( string $id, string $default = '' ): string {
		$field = $this->field( $id );
		$value = $field ? (string) ( $field['value'] ?? '' ) : '';
		return $value === '' ? $default : $value;
	}

	/**
	 * First non-empty field of a native type.
	 *
	 * @param string $type Native field type.
	 */
	public function first_of_type( string $type ): ?array {
		foreach ( $this->fields as $field ) {
			if ( is_array( $field ) && ( $field['type'] ?? '' ) === $type && (string) ( $field['value'] ?? '' ) !== '' ) {
				return $field;
			}
		}
		return null;
	}

	/**
	 * Files uploaded through one field.
	 *
	 * @param string $field_id Field id.
	 * @return Attachment[]
	 */
	public function files_for( string $field_id ): array {
		return array_values(
			array_filter(
				$this->files,
				static function ( Attachment $file ) use ( $field_id ): bool {
					return $file->field_id === $field_id;
				}
			)
		);
	}

	/** JSON-safe array. */
	public function to_array(): array {
		return [
			'id'          => $this->id,
			'uuid'        => $this->uuid,
			'form_id'     => $this->form_id,
			'form_key'    => $this->form_key,
			'post_id'     => $this->post_id,
			'element_id'  => $this->element_id,
			'source'      => $this->source,
			'form_name'   => $this->form_name,
			'fields'      => $this->fields,
			'files'       => array_map(
				static function ( Attachment $file ): array {
					return $file->to_array();
				},
				array_values( $this->files )
			),
			'lang'        => $this->lang,
			'status'      => $this->status,
			'created_gmt' => $this->created_gmt,
			'meta'        => $this->meta,
		];
	}

	/**
	 * Build from an array; fields are completed to the documented shape.
	 *
	 * @param array $a Output of to_array() or a decoded database row.
	 */
	public static function from_array( array $a ): self {
		$s              = new self();
		$s->id          = (int) ( $a['id'] ?? 0 );
		$s->uuid        = (string) ( $a['uuid'] ?? '' );
		$s->form_id     = (int) ( $a['form_id'] ?? 0 );
		$s->form_key    = (string) ( $a['form_key'] ?? '' );
		$s->post_id     = (int) ( $a['post_id'] ?? 0 );
		$s->element_id  = (string) ( $a['element_id'] ?? '' );
		$s->source      = (string) ( $a['source'] ?? 'pro' );
		$s->form_name   = (string) ( $a['form_name'] ?? '' );
		$s->lang        = (string) ( $a['lang'] ?? '' );
		$s->status      = (string) ( $a['status'] ?? 'new' );
		$s->created_gmt = (string) ( $a['created_gmt'] ?? '' );
		$s->meta        = isset( $a['meta'] ) && is_array( $a['meta'] ) ? $a['meta'] : [];

		foreach ( (array) ( $a['fields'] ?? [] ) as $key => $field ) {
			if ( ! is_array( $field ) ) {
				continue;
			}
			$id               = (string) ( $field['id'] ?? $key );
			$s->fields[ $id ] = array_merge( self::empty_field( $id ), $field );
		}
		foreach ( (array) ( $a['files'] ?? [] ) as $file ) {
			if ( $file instanceof Attachment ) {
				$s->files[] = $file;
			} elseif ( is_array( $file ) ) {
				$s->files[] = Attachment::from_array( $file );
			}
		}
		return $s;
	}

	/**
	 * Field array with every documented key.
	 *
	 * @param string $id Field id.
	 */
	private static function empty_field( string $id ): array {
		return [
			'id'       => $id,
			'type'     => 'text',
			'label'    => $id,
			'value'    => '',
			'values'   => [],
			'raw'      => '',
			'is_file'  => false,
			'redacted' => false,
			'hidden'   => false,
		];
	}
}
